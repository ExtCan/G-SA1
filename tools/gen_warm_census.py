#!/usr/bin/env python3
"""Writes addon/lua/gsa1/cl_warm_census.lua - the material census as data for the material pre-warm (cl_warm.lua) -
from core_test's material census (build/<target>/material_census.txt: every render state the six characters drew in
13 s each of scripted play with all their upgrades; 0.9.1: with the lit translucent batches' alpha, the 10th column).

    py -3.12 tools/gen_warm_census.py [CENSUS.txt] [--check]

--check: write nothing; exit 1 when the file is not what the census gives (tests/warm_test.lua fails then too, naming
this tool). The output is numbers only (archive and texture numbers, SA1_DRAW_* flags, blend factors, address modes,
passes, alphas): no game data.
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "addon", "lua", "gsa1", "cl_warm_census.lua")
NAMES = {0: "Sonic", 2: "Tails", 3: "Knuckles", 5: "Amy", 6: "E-102", 7: "Big"}


def read_census(path):
    kinds = {}
    for line in open(path, encoding="utf-8"):
        f = line.split()
        if not f or line.startswith("#"):
            continue
        k, a, t, flags, src, dst, wrap, pas = (int(f[0]), int(f[1]), int(f[2]), int(f[3], 16), int(f[4]), int(f[5]),
                                               int(f[6]), int(f[7]))
        # 0.9.1 (translucency T1): the lit translucent batches' alpha after the primitives (255: none; older censuses
        # have no such column)
        alpha = int(f[9]) if len(f) > 9 else 255
        kinds.setdefault(k, set()).add((a, t, flags, src, dst, wrap, pas, alpha))
    return kinds


def render(kinds, src_name):
    total = sum(len(v) for v in kinds.values())
    out = [
        "-- G-SA1 client: the material census as data for the material pre-warm (cl_warm.lua).",
        "-- GENERATED by tools/gen_warm_census.py from core_test's census (%s):" % src_name,
        "-- do not edit by hand; run the tool again when tests/warm_test.lua reports a census state that is not warmed",
        "-- exactly. Numbers only (archive and texture numbers of the character's own texture archives, SA1_DRAW_* flags,",
        "-- blend factors, address modes, passes, alphas): no game data. Per character kind: { archive, texture, flags, src,",
        "-- dst, wrap, pass [, alpha] } of every render state it drew in core_test's 13 s of scripted play with all its",
        "-- upgrades (%d states; the primitive kinds left out). alpha (0.9.1): a lit translucent batch's vertex alpha, its" % total,
        "-- material's $alpha (left out: 255).",
        "GSA1 = GSA1 or {}",
        "GSA1.WarmCensus = {",
    ]
    for k in sorted(kinds):
        states = sorted(kinds[k])
        out.append("    [%d] = { -- %s: %d states" % (k, NAMES.get(k, "kind %d" % k), len(states)))
        items = [("{ %d, %d, 0x%X, %d, %d, %d, %d }" % s[:7]) if s[7] == 255 else ("{ %d, %d, 0x%X, %d, %d, %d, %d, %d }" % s)
                 for s in states]
        line = "       "
        for it in items:
            if len(line) + len(it) + 2 > 118:
                out.append(line.rstrip())
                line = "       "
            line += " " + it + ","
        if line.strip():
            out.append(line.rstrip())
        out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    args = [a for a in sys.argv[1:] if a != "--check"]
    check = "--check" in sys.argv[1:]
    census = args[0] if args else os.path.join(ROOT, "build", "x86_64-windows", "material_census.txt")
    if not os.path.exists(census):
        print("no census at %s: run core_test with the disc first (build.py --test --gdi GAME.gdi)" % census)
        return 2
    try:
        rel = os.path.relpath(census, ROOT).replace("\\", "/")
    except ValueError:
        rel = os.path.basename(census)
    if rel.startswith(".."):
        rel = "material_census.txt"
    kinds = read_census(census)
    text = render(kinds, rel)
    old = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
    # the source line may name another census file of the same content: compare the data only
    strip = lambda t: "\n".join(l for l in t.splitlines() if not l.startswith("--"))
    if check:
        same = strip(old) == strip(text)
        print("%s: %s" % (os.path.relpath(OUT, ROOT), "up to date" if same else "OUT OF DATE (run tools/gen_warm_census.py)"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote %s: %d states of %d characters" % (os.path.relpath(OUT, ROOT), sum(len(v) for v in kinds.values()),
                                                     len(kinds)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
