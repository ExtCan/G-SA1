#!/usr/bin/env python3
"""Generate addon/lua/gsa1/feat/cl_wheel_rows.lua: the rows of each character's action table that cannot play in G-SA1.

    py -3.12 tools/gen_wheel_rows.py [--check] [--research DIR]

The owner (faces_wheel_plan.md 10.1, FQ19): the Emote wheel page lists the animations that cannot play too - greyed out,
not assignable, with a hover tooltip saying why in plain words. libsa1's catalogue (gsa1.EmoteList) holds only the
playable entries, so the page takes the others from this generated table: for each character entry
(GSA1.CHARACTERS name), every action-table row that the research marks as not in G-SA1's worlds (stage overlays, the
mine cart, empty rows; Sonic's Super Sonic rows; for Super Sonic (Vs. Perfect Chaos) also the board and curled-body
rows), with its number, its internal name and the reason. Source: sadc docs/research/emote_actions_<char>.tsv (res-emote,
2026-10-26). Names and numbers only (the owner rule: no game data in the addon).

--check: exit 1 when the file on disk differs from what this script would write.
"""
import argparse
import csv
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# sadc docs/research: SADC_ROOT, else ../sadc (this project's layout) or ../LibSA1/sadc (the LibSA1 repository next
# to G-SA1), the first that has it; --research overrides
RESEARCH = os.path.normpath(next(
    (os.path.join(d, "docs", "research") for d in (os.environ.get("SADC_ROOT", ""), os.path.join(ROOT, "..", "sadc"),
                                                   os.path.join(ROOT, "..", "LibSA1", "sadc"))
     if d and os.path.isdir(os.path.join(d, "docs", "research"))), os.path.join(ROOT, "..", "sadc", "docs", "research")))
OUT = os.path.join(ROOT, "addon", "lua", "gsa1", "feat", "cl_wheel_rows.lua")

# the stage overlays of Sonic's stage actions (sadc docs/research/sa1_assets.md: "Sonic's stage-specific moves")
STAGES = {
    "STG02": "Windy Valley", "STG04": "Speed Highway", "STG06": "Sky Deck", "STG07": "Lost World", "STG08": "Ice Cap",
    "STG09": "Casinopolis",
}
# GSA1.CHARACTERS entry -> its research file (and, for the two Super Sonics, the column of emote_actions_supersonic.tsv)
ENTRIES = [
    ("sonic", "sonic", None), ("tails", "tails", None), ("knuckles", "knuckles", None), ("amy", "amy", None),
    ("gamma", "gamma", None), ("big", "big", None), ("supersonic", "supersonic", "kind8"),
    ("supersonic_general", "supersonic", "general"),
]


def read_tsv(path):
    with open(path, encoding="utf-8", newline="") as f:
        lines = [l for l in f.read().split("\n") if l and not l.startswith("#")]
    return list(csv.DictReader(lines, delimiter="\t", quoting=csv.QUOTE_NONE))


def stage_reason(image, why):
    for key, title in STAGES.items():
        if key in image or key in why:
            return "%s's own animation: it needs that stage's objects - not usable yet" % title
    if "MINICART" in image or "MINICART" in why:
        return "the mine cart's animation: it needs the cart - not usable yet"
    return None


def reason_of(row, column):
    """the plain-word reason a row cannot play, or None when it plays"""
    name = row.get("internal_name") or ""
    if column is None:
        wheel = row.get("wheel", "")
        if wheel == "yes":
            return None
        cls = row.get("class", "")
        if cls == "empty":
            return "empty in the game's table: there is no animation in this row"
        if wheel == "super-only":
            return "Super Sonic's own animation: it is on the Super Sonic wheels"
        r = stage_reason(row.get("image", "") + " " + name, row.get("needs", ""))
        return r or "not in G-SA1's worlds"
    text = row.get(column, "")
    if not text.startswith("no"):
        return None
    r = stage_reason(name, text)
    if r:
        return r
    if "S_SBMOT" in text:
        return "a board animation: Super Sonic (Vs. Perfect Chaos) has no board in his world"
    if "Curled" in text:
        return "the curled-up body: the game has no golden one for Super Sonic (Vs. Perfect Chaos)"
    return "not in G-SA1's worlds"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def generate(research):
    out = []
    out.append("-- GENERATED by tools/gen_wheel_rows.py from sadc docs/research/emote_actions_*.tsv - do not edit by hand.")
    out.append("-- G-SA1 emote wheel (round 0.9.4a; owner answer FQ19, sadc docs/research/faces_wheel_plan.md 10.1): the rows of")
    out.append("-- each character's action table that cannot play in G-SA1, shown greyed out on Q menu > Options > G-SA1 > Emote")
    out.append("-- wheel with the reason as their tooltip (not assignable). Names and numbers only. W.UNPLAYABLE[entry] =")
    out.append("-- { { row, internal name, reason }, ... }; W.TABLE_ROWS[entry] = the rows of the entry's action table.")
    out.append("GSA1 = GSA1 or {}")
    out.append("GSA1.Wheel = GSA1.Wheel or {}")
    out.append("local W = GSA1.Wheel")
    out.append("W.UNPLAYABLE = {")
    counts = []
    for entry, fname, column in ENTRIES:
        rows = read_tsv(os.path.join(research, "emote_actions_%s.tsv" % fname))
        table = [r for r in rows if r.get("action", "-") not in ("-", "")]
        counts.append((entry, len(table)))
        out.append("    %s = {" % entry)
        for r in table:
            why = reason_of(r, column)
            if why is None:
                continue
            name = r.get("internal_name") or ""
            out.append("        { %d, %s, %s }," % (int(r["action"]), lua_str(name), lua_str(why)))
        out.append("    },")
    out.append("}")
    out.append("W.TABLE_ROWS = { %s }" % ", ".join("%s = %d" % (e, n) for e, n in counts))
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare with the file on disk")
    ap.add_argument("--research", default=RESEARCH, help="the folder with emote_actions_*.tsv")
    args = ap.parse_args()
    text = generate(args.research)
    if args.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("FAILED: %s differs from tools/gen_wheel_rows.py's output (run it without --check)" % OUT)
            return 1
        print("ok: %s is up to date" % os.path.relpath(OUT, ROOT))
        return 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    n = text.count("\n        { ")
    print("wrote %s (%d unplayable rows)" % (os.path.relpath(OUT, ROOT), n))
    return 0


if __name__ == "__main__":
    sys.exit(main())
